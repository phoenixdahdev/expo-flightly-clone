const byId = new Map(FLIGHT_TEMPLATES.map((t) => [t.id, t]));

export function getTemplate(id: string): FlightTemplate {
  const template = byId.get(id);
  if (!template) throw new Error(`Unknown flight template: ${id}`);
  return template;
}

export function findFlightsByRoute(fromIata: string, toIata: string): FlightTemplate[] {
  return FLIGHT_TEMPLATES.filter((t) => t.from === fromIata && t.to === toIata).sort((a, b) =>
    a.depLocal.localeCompare(b.depLocal)
  );
}
